import assert from 'node:assert/strict'
import { launchBrowser, base } from './browser.mjs'
const browser = await launchBrowser()
const storageKey = 'payment-ops.case-overrides.v1'
const upi = 'TXN-261114-0943'
const casePath = '/investigations/CASE-0943'
const requirements = ['Recipient statement or credit confirmation', 'Provider trace with final settlement status', 'Bank trace confirming final funds movement']
try {
  for (const width of [1280, 1440, 1920]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (response.status() >= 400) errors.push(response.status() + ' ' + response.url()) })
    const go = async path => assert.equal((await page.goto(base + path)).status(), 200)
    const button = name => page.getByRole('button', { name, exact: true })
    const dialog = page.getByRole('dialog')
    const getStorage = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), storageKey)
    await go(casePath)
    await page.getByRole('heading', { name: /CASE-0943.*₹943/ }).waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth))
    await page.getByText(upi, { exact: true }).waitFor()
    if (width === 1440) {
      await page.evaluate(() => document.fonts.ready)
      const geometry = await page.locator('.inv-transaction,.inv-timeline,.inv-compare,.inv-summary,.inv-checklist,.inv-activity,.inv-actions').evaluateAll(nodes => nodes.map(node => {
        const { x, y, width, height } = node.getBoundingClientRect()
        return [x, y, width, height]
      }))
      console.log('1440 px investigation panels', geometry)
    }
    await page.getByRole('button', { name: /Provider returned payment failed/ }).click()
    await dialog.getByText(/PRV-39810/).waitFor()
    await button('Close').click()
    await button('Bank Record').click()
    await dialog.getByText(/BNK-70921/).waitFor()
    await page.keyboard.press('Escape')
    await button('Record Outcome').click()
    await dialog.getByText(/All three required evidence sources/).waitFor()
    assert.equal(await button('Confirm outcome').count(), 0)
    await button('Close').click()
    assert.ok(await button('Close Case').isDisabled())

    await page.evaluate(([key, id]) => localStorage.setItem(key, JSON.stringify({
      [id]: { owner: 'Rohan M.', priority: 'High' },
      'TXN-261114-0842': { owner: 'Nisha P.', priority: 'Low' },
    })), [storageKey, upi])
    await page.reload()
    await page.getByText('Owner Rohan M.', { exact: false }).waitFor()
    await page.getByText('High Priority', { exact: true }).waitFor()
    await button('Change assignee').click()
    await dialog.getByRole('combobox', { name: 'Assignee' }).selectOption('Meera K.')
    await button('Save').click()
    await page.getByRole('status').getByText('Owner set to Meera K.').waitFor()
    await page.getByRole('button', { name: /Change priority/ }).click()
    await dialog.getByRole('combobox', { name: 'Priority' }).selectOption('Urgent')
    await button('Save').click()
    await button('Audit history').click()
    await button('Add note').click()
    await dialog.getByRole('textbox', { name: 'Case note' }).fill('Cross-check UPI settlement against the bank ledger.')
    await button('Save').click()
    await button('Request Evidence').click()
    await button('Record evidence request').click()
    await page.locator('.inv-status').getByText('Awaiting evidence').waitFor()
    await button('Escalate Case').click()
    await dialog.getByRole('textbox', { name: 'Escalation reason' }).fill('Provider report conflicts with the debit trace.')
    await button('Confirm escalation').click()
    await page.locator('.inv-status').getByText('Escalated').waitFor()
    await page.reload()
    await button('Audit history').click()
    await dialog.getByText(/Cross-check UPI settlement/).waitFor()
    await dialog.getByText(/Provider report conflicts/).waitFor()
    assert.equal(await dialog.locator('time[datetime]').count(), 5)
    const statuses = await dialog.locator('p').first().innerText()
    await button('Close').click()

    for (const [index, name] of requirements.entries()) {
      await page.getByRole('button', { name: new RegExp(name) }).click()
      await dialog.getByRole('textbox', { name: 'Verified evidence reference' }).fill('SYNTHETIC-' + index)
      await dialog.getByRole('combobox', { name: 'Verified final outcome' }).selectOption(index === 2 ? 'Refund or reversal verified' : 'Recipient credit verified')
      await button('Save').click()
    }
    await button('Record Outcome').click()
    await dialog.getByText(/verified records report conflicting outcomes/).waitFor()
    assert.equal(await button('Confirm outcome').count(), 0)
    await button('Close').click()
    await page.getByRole('button', { name: /Bank trace confirming final funds movement/ }).click()
    await dialog.getByRole('combobox', { name: 'Verified final outcome' }).selectOption('Recipient credit verified')
    await button('Save').click()

    await button('Record Outcome').click()
    const before = await getStorage()
    assert.equal(before[upi].outcome, undefined)
    await button('Confirm outcome').click()
    await page.getByRole('status').getByText('Outcome recorded · Recipient credit verified').waitFor()
    assert.equal((await getStorage())[upi].outcome, 'Recipient credit verified')
    await button('Close Case').click()
    await button('Confirm close').click()
    await page.locator('.inv-status').getByText('Closed').waitFor()
    await page.reload()
    await button('Audit history').click()
    const after = await dialog.locator('p').first().innerText()
    assert.equal(after, statuses.replace('Investigation: Escalated', 'Investigation: Closed'))
    await dialog.getByText(/Case closed · Recipient credit verified/).waitFor()
    assert.deepEqual((await getStorage())['TXN-261114-0842'], { owner: 'Nisha P.', priority: 'Low' })
    await button('Close').click()

    await page.getByRole('link', { name: 'Exception Queue', exact: true }).click()
    assert.equal(await page.locator('.case-summary dd').first().innerText(), '185')
    await button('Clear Filters').click()
    await page.getByRole('searchbox', { name: 'Search case ID, transaction ID or reference' }).fill('632114098271')
    const queueRow = page.getByRole('row').filter({ hasText: upi })
    await queueRow.getByText('Closed').waitFor()
    await queueRow.getByText('Meera K.').waitFor()
    await queueRow.getByText('Urgent').waitFor()
    await queueRow.getByRole('link', { name: 'CASE-0943' }).click()
    await page.waitForURL('**' + casePath)
    await page.getByRole('link', { name: 'Overview', exact: true }).click()
    assert.equal(await page.locator('.kpi strong').nth(2).innerText(), '185')
    await page.getByRole('searchbox', { name: 'Search transaction ID or reference' }).fill(upi)
    const overviewRow = page.getByRole('row').filter({ hasText: upi })
    await overviewRow.getByText('Closed').waitFor()
    await overviewRow.getByRole('button').click()
    await page.waitForURL('**' + casePath)
    await go('/investigations/CASE-1042')
    await page.getByText(/source reports differ/).waitFor()
    await page.getByText('Owner Nisha P.', { exact: false }).waitFor()
    await go('/investigations/CASE-0000')
    await page.getByRole('heading', { name: 'Case unavailable' }).waitFor()
    assert.deepEqual(errors, [])
    console.log(width + ' px passed routes, evidence inspection, resolution gates, action history, legacy storage and cross-screen updates')
    await page.close()
  }
} finally {
  await browser.close()
}
