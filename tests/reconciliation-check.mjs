import assert from 'node:assert/strict'
import { launchBrowser, base } from './browser.mjs'

const browser = await launchBrowser()
const key = 'payment-ops.case-overrides.v1'
const upi = 'TXN-261114-0943'
try {
  for (const width of [1280, 1440, 1920]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (response.status() >= 400) errors.push(response.status() + ' ' + response.url()) })
    const button = name => page.getByRole('button', { name, exact: true })
    const dialog = page.getByRole('dialog')
    const search = page.getByRole('searchbox', { name: 'Search transaction or reference…', exact: true })
    const summaries = () => page.locator('.recon-summary dd').allTextContents()
    const storage = () => page.evaluate(storageKey => JSON.parse(localStorage.getItem(storageKey) ?? '{}'), key)
    const go = async route => assert.equal((await page.goto(base + route))?.status(), 200)
    await go('/reconciliation')
    assert.deepEqual(await summaries(), ['1,248','14','18','24'])
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth))
    assert.equal(await page.locator('[aria-current=page]').innerText(), 'Reconciliation')
    assert.equal(await page.locator('tbody tr').count(), 8)
    await page.getByRole('heading', { name: 'Selected record · TXN-261114-0842' }).waitFor()
    if (width === 1440) {
      await page.evaluate(() => document.fonts.ready)
      console.log('1440 px geometry', await page.locator('.overview-heading,.recon-summary,.recon-records,.recon-compare,.recon-source,.recon-next').evaluateAll(nodes => nodes.map(node => {
        const {x,y,width,height} = node.getBoundingClientRect()
        return [x,y,width,height]
      })))
    }
    const verified = page.getByRole('checkbox', { name: 'Supporting evidence verified' })
    await verified.check()
    assert.ok(await button('Confirm Match').isDisabled())
    await button('Open Investigation').click()
    await page.waitForURL('**/investigations/CASE-1042')
    await page.getByRole('link', { name: 'Reconciliation', exact: true }).click()
    await button('Next page').click()
    await page.getByText('Page 2 of 7').waitFor()
    await button('Previous page').click()
    await page.getByText('Page 1 of 7').waitFor()

    await page.getByRole('button', { name: 'Settlement Discrepancies 18' }).click()
    await page.getByRole('combobox', { name: 'All statuses' }).selectOption('Reference mismatch')
    await page.locator('.recon-source dd.recon-field-difference').first().waitFor()
    assert.ok(await button('Confirm Match').isDisabled())
    await page.getByRole('combobox', { name: 'All statuses' }).selectOption('Settlement discrepancy')
    assert.equal(await page.locator('.recon-source dd.recon-field-difference').count(), 2)
    await button('Link Investigation').click()
    await page.getByRole('status').getByText(/Reconciliation linked to CASE-/).waitFor()
    await button('Open Investigation').waitFor()
    await page.getByRole('button', { name: 'Unmatched Records 56' }).click()
    await page.getByRole('combobox', { name: 'All providers' }).selectOption('SettlePay')
    assert.ok(await page.locator('tbody tr').count() > 0)
    await page.getByRole('combobox', { name: 'Reconciliation date range' }).selectOption('all')
    assert.ok(Number((await summaries())[1]) > 14)
    await button('Filter').click()
    await button('Clear filters').click()
    await button('Bank Amount').click()
    assert.equal(await page.getByRole('columnheader', { name: /Bank Amount/ }).getAttribute('aria-sort'), 'descending')
    await search.fill('80432')
    await page.getByText('A source record has already been matched to another transaction.').waitFor()
    await verified.check()
    assert.ok(await button('Confirm Match').isDisabled())
    await search.fill('80427')
    await page.getByText('Not calculable', { exact: true }).waitFor()
    assert.ok(await button('Confirm Match').isDisabled())
    await button('Request Evidence').click()
    await dialog.getByRole('textbox', { name: 'Evidence to request' }).fill('Supply bank trace for 80427.')
    await button('Record evidence request').click()
    await page.getByRole('status').getByText(/Supply bank trace/).waitFor()
    await page.getByRole('button', { name: /View audit history/ }).click()
    await dialog.getByText(/Supply bank trace/).waitFor()
    await button('Close').click()

    await page.evaluate(([storageKey, id]) => {
      const saved = JSON.parse(localStorage.getItem(storageKey))
      saved[id] = { owner: 'Meera K.', priority: 'High', history: [{ at: '2026-11-17T08:00:00Z', text: 'Legacy owner edit' }] }
      localStorage.setItem(storageKey, JSON.stringify(saved))
    }, [key, upi])
    await page.reload()
    await search.fill('632114098271')
    await page.getByRole('heading', { name: 'Selected record · ' + upi, exact: true }).waitFor()
    assert.equal(await page.locator('.recon-source-amount strong').first().innerText(), '₹943.00')
    assert.ok(await button('Confirm Match').isDisabled())
    await verified.check()
    await button('Confirm Match').click()
    assert.equal((await storage())[upi].reconciliation, undefined)
    await dialog.getByRole('textbox', { name: 'Supporting evidence reference or note' }).fill('   ')
    await button('Confirm manual match').click()
    await dialog.getByRole('alert').getByText(/provide supporting evidence/).waitFor()
    await dialog.getByRole('textbox', { name: 'Supporting evidence reference or note' }).fill('BANK-TRACE-943 / PROVIDER-943')
    await button('Confirm manual match').click()
    await page.getByRole('status').getByText(/Manual match confirmed/).waitFor()
    assert.deepEqual(await summaries(), ['1,249','14','18','23'])
    assert.ok(await button('Confirm Match').isDisabled())
    const after = (await storage())[upi]
    assert.equal(after.owner, 'Meera K.')
    assert.equal(after.priority, 'High')
    assert.equal(after.investigation, undefined)
    assert.equal(after.reconciliation.matched, true)
    assert.equal(after.reconciliation.events.filter(event => event.kind === 'match').length, 1)
    await page.reload()
    await button('Reconciliation History').click()
    await search.fill(upi)
    await page.getByRole('heading', { name: 'Selected record · ' + upi, exact: true }).waitFor()
    await page.getByRole('button', { name: /View audit history/ }).click()
    await dialog.getByText(/BANK-TRACE-943/).waitFor()
    await dialog.getByText(/Owner Meera K./).waitFor()
    await button('Close').click()
    await button('Link Investigation').click()
    await button('Open Investigation').click()
    await page.waitForURL('**/investigations/CASE-0943')
    await button('Audit history').click()
    await dialog.getByText(/Payment: Pending · Investigation: Investigating · Reconciliation: Matched/).waitFor()
    await dialog.getByText('Legacy owner edit').waitFor()
    await dialog.getByText(/Manual match confirmed/).waitFor()
    await button('Close').click()

    await page.getByRole('link', { name: 'Overview', exact: true }).click()
    assert.deepEqual(await page.locator('.kpi strong').allTextContents(), ['248','42','186','18'])
    await page.getByRole('searchbox', { name: 'Search transaction ID or reference', exact: true }).fill(upi)
    await page.getByRole('row').filter({ hasText: upi }).getByText('Meera K.').waitFor()
    await button('View All Exceptions').click()
    await page.getByRole('searchbox', { name: 'Search case ID, transaction ID or reference', exact: true }).fill(upi)
    const queueRow = page.getByRole('row').filter({ hasText: upi })
    await queueRow.getByText('Meera K.').waitFor()
    await queueRow.getByText('Investigating').waitFor()
    await queueRow.getByText('Pending').waitFor()
    assert.deepEqual(errors, [])
    console.log(width + ' px passed reconciliation layout, search, filters, sort, pagination, link, evidence request, matching, blocking, history and shared-record persistence')
    await page.close()
  }
} finally {
  await browser.close()
}
